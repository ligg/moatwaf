from __future__ import annotations

from collections import Counter
from typing import Any, Iterable

from security_automation.models import SEVERITY_ORDER


ACTIONABLE_SEVERITIES = {"critical", "high"}


def _sorted_findings(findings: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    return sorted(
        findings,
        key=lambda item: (
            0 if item.get("kev") else 1,
            SEVERITY_ORDER.get(str(item.get("severity", "unknown")), 4),
            str(item.get("id", "")),
            str(item.get("purl", "")),
        ),
    )


def _counts(findings: list[dict[str, Any]]) -> Counter[str]:
    counts: Counter[str] = Counter(total=len(findings))
    for item in findings:
        severity = str(item.get("severity", "unknown"))
        counts[severity if severity in SEVERITY_ORDER else "unknown"] += 1
        if item.get("kev"):
            counts["kev"] += 1
    return counts


def _identifier(item: dict[str, Any]) -> str:
    cve_ids = item.get("cveIds", [])
    if cve_ids:
        return str(cve_ids[0])
    return str(item.get("id", "unknown"))


def _escape(value: Any) -> str:
    return str(value if value not in (None, "") else "-").replace("|", "\\|").replace("\n", " ")


def _finding_row(item: dict[str, Any]) -> str:
    fixed = ", ".join(item.get("fixedVersions", [])) or "No fix listed"
    rule_family = item.get("ruleFamily") or "Unmapped"
    return (
        f"| {_escape(_identifier(item))} | {_escape(item.get('component'))} "
        f"{_escape(item.get('version'))} | {_escape(item.get('severity'))} | "
        f"{_escape(fixed)} | {_escape(rule_family)} |"
    )


def render_report(scan: dict[str, Any]) -> str:
    findings = _sorted_findings(scan.get("findings", []))
    counts = _counts(findings)
    lines = [
        "# Moat WAF Vulnerability Intelligence Report",
        "",
        f"Generated: `{scan.get('generatedAt', 'unknown')}`",
        f"Components scanned: `{scan.get('components', 0)}`",
        "",
        "## Summary",
        "",
        "| Metric | Count |",
        "|---|---:|",
        f"| Total findings | {counts['total']} |",
        f"| Known exploited | {counts['kev']} |",
        f"| Critical | {counts['critical']} |",
        f"| High | {counts['high']} |",
        f"| Medium | {counts['medium']} |",
        f"| Low | {counts['low']} |",
        f"| Unknown | {counts['unknown']} |",
        "",
        "## Priority findings",
        "",
    ]
    if findings:
        lines.extend(
            [
                "| CVE / Advisory | Component | Severity | Fixed version | Rule family |",
                "|---|---|---|---|---|",
                *[_finding_row(item) for item in findings],
            ]
        )
    else:
        lines.append("No vulnerabilities matched the current SBOM.")

    family_counts = Counter(
        item.get("ruleFamily") or "Unmapped" for item in findings
    )
    lines.extend(["", "## Rule-family coverage", ""])
    if family_counts:
        lines.extend(
            [f"- `{family}`: {count} finding(s)" for family, count in sorted(family_counts.items())]
        )
    else:
        lines.append("- No rule-family mapping required.")

    lines.extend(["", "## Next actions", ""])
    if findings:
        lines.extend(
            [
                "1. Confirm that each affected component and version is present in the deployed image.",
                "2. Upgrade components with available fixed versions and rebuild the image.",
                "3. For known exploited findings without a fix, add a reviewed temporary WAF rule.",
                "4. Re-run the scan and the Lua regression suite before release.",
            ]
        )
    else:
        lines.append("No immediate action is required from this scan.")

    errors = scan.get("errors", [])
    if errors:
        lines.extend(["", "## Collection errors", ""])
        lines.extend(f"- {error}" for error in errors)

    nvd_enriched = scan.get("nvdEnriched")
    if nvd_enriched is False:
        lines.extend(
            [
                "",
                "NVD enrichment was skipped. Configure `NVD_API_KEY` to enrich CVSS data.",
            ]
        )
    return "\n".join(lines) + "\n"


def render_issue(scan: dict[str, Any]) -> str:
    findings = _sorted_findings(scan.get("findings", []))
    actionable = [
        item
        for item in findings
        if item.get("kev") or item.get("severity") in ACTIONABLE_SEVERITIES
    ]
    counts = _counts(findings)
    lines = [
        "<!-- security-intel:rolling -->",
        "Automatically generated by the Moat WAF security intelligence workflow.",
        "",
        f"- Scan time: `{scan.get('generatedAt', 'unknown')}`",
        f"- Components scanned: `{scan.get('components', 0)}`",
        f"- Total findings: `{counts['total']}`",
        f"- Known exploited: `{counts['kev']}`",
        f"- Actionable critical/high/KEV findings: `{len(actionable)}`",
        "",
    ]
    if actionable:
        lines.extend(
            [
                "| CVE / Advisory | Component | Severity | Fixed version |",
                "|---|---|---|---|",
            ]
        )
        for item in actionable[:30]:
            fixed = ", ".join(item.get("fixedVersions", [])) or "No fix listed"
            lines.append(
                f"| {_escape(_identifier(item))} | {_escape(item.get('component'))} "
                f"{_escape(item.get('version'))} | {_escape(item.get('severity'))} | "
                f"{_escape(fixed)} |"
            )
        if len(actionable) > 30:
            lines.append(f"\nShowing 30 of {len(actionable)} actionable findings.")
        lines.extend(
            [
                "",
                "Next action: confirm deployment impact, upgrade fixed components, and add",
                "reviewed temporary WAF rules only where a fix is unavailable.",
            ]
        )
    else:
        lines.append("No critical, high, or known-exploited findings were detected.")

    if scan.get("errors"):
        lines.extend(["", f"Collection warnings: `{len(scan['errors'])}` (see report artifact)."])
    return "\n".join(lines) + "\n"

